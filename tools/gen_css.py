def build(theme):
    t = dict(THEMES[theme])
    for k in ('text', 'link', 'code', 'file', 'image'):
        t[f'k_{k}_a'] = rgba(t[f'k_{k}'], 0.15)
    css = BASE.format(**t)
    for name, cols in ACCENTS.items():
        base, fg = cols[0], cols[t['fg_idx']]
        css += ACCENT.format(name=name, base=base, fg=fg, text=t['text'],
                             sel=rgba(base, t['sel_alpha']), ring=rgba(base, 0.7),
                             selbg=rgba(base, 0.4), chipbg=rgba(base, 0.2))
    return css + '\n'


for theme in THEMES:
    with open(os.path.join(OUT, f'stylesheet-{theme}.css'), 'w') as f:
        f.write(build(theme))
with open(os.path.join(OUT, 'stylesheet.css'), 'w') as f:
    f.write(build('dark'))
print('css ok')
